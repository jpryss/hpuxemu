#!/usr/bin/env python3
"""genrust.py - rust/hpuxemu/src/consts.rs from hpuxemu/consts.py, consts11.py and
scall11.py (themselves generated from the root's headers by tools/genconsts.py and
tools/genscall11.py), so that the Rust emulator and the Python one share one source of
constants, structure layouts and system call numbers.

    python3 tools/genrust.py
"""
import keyword
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from hpuxemu import consts, consts11, scall11      # noqa: E402

RUST_KEYWORDS = {'as', 'break', 'const', 'continue', 'crate', 'else', 'enum', 'extern', 'false', 'fn', 'for', 'if',
                 'impl', 'in', 'let', 'loop', 'match', 'mod', 'move', 'mut', 'pub', 'ref', 'return', 'self', 'Self',
                 'static', 'struct', 'super', 'trait', 'true', 'type', 'unsafe', 'use', 'where', 'while', 'async',
                 'await', 'dyn', 'abstract', 'become', 'box', 'do', 'final', 'macro', 'override', 'priv', 'typeof',
                 'unsized', 'virtual', 'yield', 'try'}


def ident(n):
    return 'r#' + n if n in RUST_KEYWORDS else n


def layouts(out, modname, offset, sizeof):
    out.append('/// structure layouts: `SIZE` and each member as F(offset, size)')
    out.append('pub mod %s {' % modname)
    out.append('    use super::F;')
    for s in sorted(offset):
        out.append('    pub mod %s {' % ident(s.lstrip('_') if s.startswith('__') else s))
        out.append('        use super::F;')
        out.append('        pub const SIZE: usize = %d;' % sizeof[s])
        for m, (off, size) in sorted(offset[s].items(), key=lambda kv: kv[1]):
            out.append('        pub const %s: F = F(%d, %d);' % (ident(m), off, size))
        out.append('    }')
    out.append('}')


def table(out, name, d):
    out.append('pub static %s: &[(u32, &str)] = &[' % name)
    for k in sorted(d):
        out.append('    (%d, "%s"),' % (k, d[k]))
    out.append('];')


def main():
    out = ['// consts.rs - generated by tools/genrust.py from hpuxemu/consts.py, consts11.py and',
           '// scall11.py (the root\'s headers; do not edit).',
           '#![allow(non_upper_case_globals, dead_code, non_camel_case_types, unused_imports)]',
           '',
           '/// a structure member: (offset, size)',
           '#[derive(Clone, Copy)]',
           'pub struct F(pub usize, pub usize);',
           '']
    for k in sorted(consts.C):
        v = consts.C[k]
        if not isinstance(v, int):
            continue
        if 0 <= v < 1 << 32:
            out.append('pub const %s: u32 = %#x;' % (ident(k), v))
        elif -(1 << 31) <= v < 0:
            out.append('pub const %s: i32 = %d;' % (ident(k), v))
        else:
            out.append('pub const %s: i64 = %d;' % (ident(k), v))
    out.append('')
    layouts(out, 'off', consts.OFFSET, consts.SIZEOF)
    layouts(out, 'off11', consts11.OFFSET, consts11.SIZEOF)
    # the pstat structures by member name, in both layouts (pstat fills what a layout has)
    for name, offset in (('PST_10', consts.OFFSET), ('PST_64', consts11.OFFSET)):
        out.append('pub static %s: &[(&str, &str, F)] = &[' % name)
        for s in sorted(offset):
            if s.startswith('pst_'):
                for m, (off, size) in sorted(offset[s].items(), key=lambda kv: kv[1]):
                    out.append('    ("%s", "%s", F(%d, %d)),' % (s, m, off, size))
        out.append('];')
    table(out, 'SYSCALLS_10', consts.SYSCALL_NAMES)
    table(out, 'SYSCALLS_11', scall11.SYSCALL_NAMES_11)
    table(out, 'ERRNO_NAMES', consts.ERRNO_NAMES)
    table(out, 'SIGNAL_NAMES', consts.SIGNAL_NAMES)
    # host (Linux) errno -> HP-UX errno and HP-UX signal -> host signal, by name
    import errno
    import signal
    h2g = {}
    for num, name in errno.errorcode.items():
        if name != 'EWOULDBLOCK' and name in consts.C:
            h2g[num] = consts.C[name]
    h2g[errno.EAGAIN] = consts.C['EAGAIN']
    h2g[errno.ENOTSUP] = consts.C.get('ENOTSUP', consts.C['EOPNOTSUPP'])
    out.append('/// host (Linux) errno -> HP-UX errno')
    out.append('pub static HOST_ERRNO: &[(i32, u32)] = &[')
    for k in sorted(h2g):
        out.append('    (%d, %d),' % (k, h2g[k]))
    out.append('];')
    out.append('/// (HP-UX signal, host signal) for the signals both have by name')
    out.append('pub static HOST_SIGNALS: &[(u32, i32)] = &[')
    for num in sorted(consts.SIGNAL_NAMES):
        h = getattr(signal, consts.SIGNAL_NAMES[num], None)
        if h is not None:
            out.append('    (%d, %d),' % (num, int(h)))
    out.append('];')
    p = os.path.join(os.path.dirname(HERE), 'rust', 'hpuxemu', 'src', 'consts.rs')
    with open(p, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('%s: %d lines' % (p, len(out)))


if __name__ == '__main__':
    main()
