#!/usr/bin/env python3
"""Generate docs/SYSCALLS.md from the sys_* docstrings in hpuxemu/emu.py and the system
call numbers of sys/syscall.h (hpuxemu/consts.py).

    python3 tools/syscalls_doc.py > docs/SYSCALLS.md

Every sys_* handler's docstring is its specification line; this tool arranges them by
the "# ---- section ----" comments of the Process class, flags stubs (a constant result
or a fixed error), and lists the numbers the kernel has that are not implemented."""
import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))

from hpuxemu.consts import SYSCALL_NAMES  # noqa: E402

SRC = os.path.join(HERE, '..', 'hpuxemu', 'emu.py')


def load():
    src = open(SRC).read()
    tree = ast.parse(src)
    lines = src.splitlines()
    cls = [n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == 'Process'][0]
    sections = []
    for i, l in enumerate(lines, 1):
        m = re.match(r'    # -{2,4} (.*?) -*$', l)
        if m:
            sections.append((i, m.group(1).strip()))
    handlers = []
    for f in cls.body:
        if isinstance(f, ast.FunctionDef) and f.name.startswith('sys_'):
            sec = ''
            for ln, name in sections:
                if ln < f.lineno:
                    sec = name
            args = [a.arg for a in f.args.args[1:]]
            if f.args.vararg:
                args = [a for a in args]
            doc = ast.get_docstring(f) or ''
            body = f.body[1:] if (f.body and isinstance(f.body[0], ast.Expr) and isinstance(getattr(f.body[0], 'value', None), ast.Constant)) else f.body
            stub = len(body) == 1 and ((isinstance(body[0], ast.Return) and isinstance(body[0].value, ast.Constant)) or isinstance(body[0], ast.Raise))
            handlers.append(dict(name=f.name[4:], args=args, doc=' '.join(doc.split()), section=sec, stub=stub))
    # aliases: "sys_vfork = sys_fork"
    aliases = {}
    for node in cls.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Name) and node.value.id.startswith('sys_'):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id.startswith('sys_'):
                    aliases[t.id[4:]] = node.value.id[4:]
    return handlers, aliases


def main():
    handlers, aliases = load()
    by_name = {h['name']: h for h in handlers}
    numbers = {}        # handler -> [(number, kernel name)]
    unimplemented = []
    for num, name in sorted(SYSCALL_NAMES.items()):
        target = name if name in by_name else aliases.get(name)
        if target:
            numbers.setdefault(target, []).append((num, name))
        else:
            unimplemented.append((num, name))
    out = []
    w = out.append
    w('# System calls\n')
    w('*Generated by `tools/syscalls_doc.py` from the docstrings in `hpuxemu/emu.py`; do not edit by hand.*\n')
    w('HP-UX programs enter the kernel through the gateway page: `ldil L%0xc0000000,r1; ble 4(sr7,r1)`')
    w('with the call number in r22 (loaded in the delay slot), the first four arguments in')
    w('r26-r23 and the rest at -52(sp), -56(sp) ...; the result comes back in r28 (r29 for a')
    w('second value), r22 = 0 on success and 1 on failure with the errno in r28, and execution')
    w('resumes at r31. The emulator dispatches the number to `Process.sys_<name>` with the name')
    w('`sys/syscall.h` gives it ([ABI.md](ABI.md) has the conventions and structures).\n')
    n_impl = len([h for h in handlers if not h['stub']])
    n_stub = len([h for h in handlers if h['stub']])
    covered = sum(len(v) for v in numbers.values())
    w('**%d handlers** (%d real, %d accept-and-ignore stubs) cover **%d of the %d numbers** of'
      % (len(handlers), n_impl, n_stub, covered, len(SYSCALL_NAMES)))
    w('HP-UX 10.20\'s `syscall.h`; the remaining %d are listed at the end. A handler marked *stub*' % len(unimplemented))
    w('returns a constant or an error without doing anything.\n')
    cur = None
    for h in handlers:
        if h['section'] != cur:
            cur = h['section']
            w('\n## %s\n' % (cur[0].upper() + cur[1:] if cur else 'Other'))
            w('| number | HP-UX name | handler | notes |')
            w('|---|---|---|---|')
        nums = numbers.get(h['name'], [])
        numcol = ', '.join(str(n) for n, _ in nums) or '-'
        names = ', '.join('`%s`' % n for _, n in nums) or '*(internal)*'
        flag = ' *(stub)*' if h['stub'] else ''
        w('| %s | %s | `sys_%s`%s | %s |' % (numcol, names, h['name'], flag, h['doc'].replace('|', '\\|')))
    w('\n## Not implemented\n')
    w('These numbers of `syscall.h` have no handler: the emulator prints `unimplemented syscall`')
    w('and returns ENOSYS. Most are kernel administration, the kernel threads of 10.30 and')
    w('later, or networking not yet reached by the programs tried.\n')
    w(', '.join('`%s` (%d)' % (n, num) for num, n in unimplemented))
    w('')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
