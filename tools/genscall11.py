#!/usr/bin/env python3
"""genscall11.py - write hpuxemu/scall11.py, the HP-UX 11.00 system call numbers, from an
11.00 root's /usr/include/sys/scall_define.h:

    python3 tools/genscall11.py ROOT11

11.00 renumbered some calls of 10.20 (the lwp_*, sigwait and mq_* groups), dropped the
cluster and NetIPC ones and added others (pread/pwrite, siginhibit/sigenable,
statvfs64, sendfile ...). The emulator decodes with this table when the root's
etc/hpuxemu/release is B.11.*; the handlers are the same, looked up by name."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    names = {}
    for line in open(os.path.join(argv[1], 'usr/include/sys/scall_define.h'), encoding='latin1'):
        m = re.match(r'^#\s*define\s+SYS_([a-z][a-z0-9_]*)\s+(\d+)\b', line)
        if m:
            names.setdefault(int(m.group(2)), m.group(1))
    out = os.path.join(HERE, '..', 'hpuxemu', 'scall11.py')
    with open(out, 'w') as f:
        f.write('"""scall11.py - HP-UX 11.00 system call numbers, generated by tools/genscall11.py\n'
                'from an 11.00 root\'s /usr/include/sys/scall_define.h (do not edit)."""\n\n')
        f.write('SYSCALL_NAMES_11 = {\n')
        for n in sorted(names):
            f.write('    %d: %r,\n' % (n, names[n]))
        f.write('}\n')
    print('%s: %d calls' % (out, len(names)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
